"""Generate the packaged printable ASCII subset of two console fonts."""

import argparse
import gzip
import struct
from pathlib import Path


def read_psf(path):
    """Read glyphs by Unicode codepoint, ignoring multi-codepoint aliases."""
    data = gzip.decompress(path.read_bytes())
    if data.startswith(b"\x36\x04"):
        _, mode, stride = struct.unpack_from("<2sBB", data)
        if not mode & 6:
            raise ValueError("PSF1 font has no Unicode table")
        width, height, start, count = 8, stride, 4, 512 if mode & 1 else 256
        table = data[start + count * stride:]
        entries = []
        codepoints = []
        sequence = False
        for (codepoint,) in struct.iter_unpack("<H", table):
            if codepoint == 0xFFFF:
                entries.append(codepoints)
                codepoints = []
                sequence = False
            elif codepoint == 0xFFFE:
                sequence = True
            elif not sequence:
                codepoints.append(chr(codepoint))
        aliases = entries
    elif data.startswith(b"\x72\xb5\x4a\x86"):
        _, version, start, flags, count, stride, height, width = struct.unpack_from("<8I", data)
        if version != 0 or not flags & 1:
            raise ValueError("expected PSF2 version 0 with a Unicode table")
        table = data[start + count * stride:]
        aliases = (entry.split(b"\xfe", 1)[0].decode("utf-8") for entry in table.split(b"\xff"))
    else:
        raise ValueError("unrecognized PSF format")
    if width != 8 or stride != height:
        raise ValueError("expected glyphs with one byte per row")
    glyphs = {}
    for index, entry in zip(range(count), aliases):
        offset = start + index * stride
        for char in entry:
            if " " <= char <= "~":
                glyphs.setdefault(char, data[offset:offset + stride])
    return height, [glyphs[chr(cp)] for cp in range(0x20, 0x7F)]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--font-dir", type=Path, default=Path("/usr/share/consolefonts"))
    parser.add_argument("--output", type=Path, default=Path(__file__).resolve().parents[1]
                        / "printer_goblin/payloads/font_fixed.py")
    args = parser.parse_args()
    lines = ['"""Glyphs from the X11 misc-fixed fonts (public domain) via console-setup."""',
             "", "# Generated by tools/make_font.py. One byte per row, MSB at left."]
    for size in (16, 18):
        height, glyphs = read_psf(args.font_dir / f"Lat15-Fixed{size}.psf.gz")
        if height != size:
            raise ValueError(f"expected {size}-row glyphs")
        lines.extend(["", f"FIXED_{size} = bytes.fromhex("])
        lines.extend(f'    "{glyph.hex()}"  # {chr(index + 0x20)!r}'
                     for index, glyph in enumerate(glyphs))
        lines.append(")")
    args.output.write_text("\n".join(lines) + "\n", encoding="ascii")


if __name__ == "__main__":
    main()
